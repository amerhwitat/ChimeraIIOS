#!/usr/bin/env bash
# Install GRUB 2 for an already-deployed Chimera root filesystem.
# Usage: install-grub2.sh TARGET_ROOT BOOT_DEVICE bios|uefi [EFI_DIRECTORY]
set -euo pipefail

fail() { printf 'GRUB install: %s\n' "$*" >&2; exit 1; }
[[ $# -ge 3 && $# -le 4 ]] || fail "usage: $0 TARGET_ROOT BOOT_DEVICE bios|uefi [EFI_DIRECTORY]"
ROOT=$(realpath -e "$1") || fail "target root does not exist"
BOOT_DEVICE=$2
FIRMWARE=$3
EFI_DIR=${4:-"$ROOT/boot/efi"}

[[ -d "$ROOT/etc" && -d "$ROOT/boot" ]] || fail "target root must contain etc/ and boot/"
[[ -f "$ROOT/etc/chimera/install.conf" ]] || fail "not a deployed Chimera root (missing /etc/chimera/install.conf)"
[[ -f "$ROOT/boot/koronos/koronos.elf" ]] || fail "installed Koronos ELF missing"
[[ -b "$BOOT_DEVICE" ]] || fail "boot device must be an existing block device"
command -v grub-install >/dev/null || fail "grub-install is not installed"
command -v blkid >/dev/null || fail "blkid is required"
command -v grub-script-check >/dev/null || fail "grub-script-check is required"

ROOT_SOURCE=$(findmnt -n -o SOURCE --target "$ROOT" 2>/dev/null || true)
[[ -n "$ROOT_SOURCE" ]] || fail "cannot identify the filesystem containing target root"
ROOT_UUID=$(blkid -s UUID -o value "$ROOT_SOURCE" 2>/dev/null || true)
[[ -n "$ROOT_UUID" ]] || fail "target root filesystem has no UUID; refusing an unstable boot reference"

install -d "$ROOT/boot/grub"
cat > "$ROOT/boot/grub/grub.cfg" <<CFG
# Generated by Chimera II installer. Root UUID: $ROOT_UUID
set default=0
set timeout=5
insmod part_gpt
insmod part_msdos
insmod ext2
insmod fat
insmod search
insmod search_fs_uuid
insmod multiboot2
insmod all_video
insmod gfxterm
set gfxmode=1920x1080,1280x720,1024x768,800x600,640x480,auto
set gfxpayload=keep
terminal_output gfxterm
search --no-floppy --fs-uuid --set=root $ROOT_UUID

menuentry "Chimera II OS — Installed System (Koronos / Aurora)" --id chimera-installed {
    if [ -f /boot/koronos/koronos.elf ] && [ -f /boot/live/chimera-live-initramfs.img ]; then
        multiboot2 /boot/koronos/koronos.elf chm.target=installed chm.log=verbose chm.progress=events
        module2 /boot/live/chimera-live-initramfs.img chimera-installed-initramfs
        if [ -f /boot/live/live-manifest.json ]; then
            module2 /boot/live/live-manifest.json chimera-installed-manifest
        fi
        boot
    else
        echo "Installed Koronos kernel/initramfs missing; refusing fallback to installer media."
        sleep 10
    fi
}
menuentry "Chimera II OS — Recovery" --id chimera-recovery {
    if [ -f /boot/recovery/chimera-recovery-initramfs.img ]; then
        multiboot2 /boot/koronos/koronos.elf chm.target=recovery chm.log=verbose
        module2 /boot/recovery/chimera-recovery-initramfs.img chimera-recovery-initramfs
        boot
    else
        echo "Recovery initramfs missing."
        sleep 5
    fi
}
menuentry "Reboot" { reboot }
menuentry "Power off" { halt }
CFG

grub-script-check "$ROOT/boot/grub/grub.cfg" || fail "generated GRUB configuration failed syntax validation"

case "$FIRMWARE" in
  bios)
    grub-install --target=i386-pc --boot-directory="$ROOT/boot" --recheck "$BOOT_DEVICE"
    ;;
  uefi)
    [[ -d "$EFI_DIR" ]] || fail "EFI system partition must be mounted at $EFI_DIR"
    grep -qiE 'vfat|fat' < <(findmnt -n -o FSTYPE --target "$EFI_DIR") || fail "EFI directory is not on a FAT filesystem"
    grub-install --target=x86_64-efi --efi-directory="$EFI_DIR" --boot-directory="$ROOT/boot" --bootloader-id=ChimeraIIOS --recheck
    ;;
  *) fail "firmware must be bios or uefi" ;;
esac

grub-script-check "$ROOT/boot/grub/grub.cfg" || fail "generated GRUB configuration failed syntax validation"
printf 'GRUB 2 installed for %s. Root UUID=%s\n' "$FIRMWARE" "$ROOT_UUID"
printf 'Next boot entry: Chimera II OS — Installed System (Koronos / Aurora)\n'
